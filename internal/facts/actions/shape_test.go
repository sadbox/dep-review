				fs := setupGoBump(t)
				fs[1].Base = []byte(edit(t, string(fs[1].Base), "actions/setup-go", "Actions/Setup-Go"))
				fs[1].Head = []byte(edit(t, string(fs[1].Head), "actions/setup-go", "Actions/Setup-Go"))
