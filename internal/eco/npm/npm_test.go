func tree(t *testing.T, files map[string]string) *ecoutil.Tree {
	t.Helper()
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	tw := tar.NewWriter(zw)
	for _, name := range slices.Sorted(func(yield func(string) bool) {
		for k := range files {
			if !yield(k) {
				return
			}
		}
	}) {
		if err := tw.WriteHeader(&tar.Header{Name: "package/" + name, Mode: 0o644, Size: int64(len(files[name])), Typeflag: tar.TypeReg}); err != nil {
			t.Fatal(err)
		}
		tw.Write([]byte(files[name]))
	}
	tw.Close()
	zw.Close()
	p := filepath.Join(t.TempDir(), "p.tgz")
	os.WriteFile(p, buf.Bytes(), 0o644)
	tr, err := ecoutil.ExtractTarGz(p, filepath.Join(t.TempDir(), "x"), true)
	if err != nil {
		t.Fatal(err)
	}
	return tr
}

func mkSide(t *testing.T, pkgJSON string, extra map[string]string, docJSON string) *side {
	t.Helper()
	files := map[string]string{"package.json": pkgJSON}
	for k, v := range extra {
		files[k] = v
	}
	s := &side{tree: tree(t, files), doc: &versionDoc{}}
	if err := json.Unmarshal([]byte(pkgJSON), &s.pkg); err != nil {
		t.Fatal(err)
	}
	if docJSON == "" {
		docJSON = pkgJSON
	}
	if err := json.Unmarshal([]byte(docJSON), s.doc); err != nil {
		t.Fatal(err)
	}
	return s
}

func TestCheckPackage(t *testing.T) {
	const basePkg = `{"name":"p","version":"1.0.0","dependencies":{"a":"^1"},"bin":{"p":"cli.js"},"_npmUser":{"name":"alice","email":"a@x"},"maintainers":[{"name":"alice"}],"dist":{"attestations":{"provenance":{"predicateType":"https://slsa.dev/provenance/v1"}}}}`
	minified := strings.Repeat("var a=function(b){return b+1};", 200)
	tests := []struct {
		name  string
		pkg   string
		doc   string
		extra map[string]string
		want  []string
	}{
		{"same", basePkg, "", nil, nil},
		{"postinstall", strings.Replace(basePkg, `"version"`, `"scripts":{"postinstall":"node x.js"},"version"`, 1), "", nil, []string{"npm.install-script"}},
		{"new bin", strings.Replace(basePkg, `{"p":"cli.js"}`, `{"p":"cli.js","q":"q.js"}`, 1), "", nil, []string{"npm.new-bin"}},
		{"new dep", strings.Replace(basePkg, `{"a":"^1"}`, `{"a":"^1","b":"^2"}`, 1), "", nil, []string{"npm.new-package-dependency"}},
		{"publisher", strings.Replace(basePkg, `"alice","email"`, `"mallory","email"`, 1), "", nil, []string{"npm.publisher-changed"}},
		{"maintainers", strings.Replace(basePkg, `[{"name":"alice"}]`, `[{"name":"alice"},{"name":"bob"}]`, 1), "", nil, []string{"npm.maintainers-changed"}},
		{"provenance lost", strings.Replace(basePkg, `"dist":{"attestations":{"provenance":{"predicateType":"https://slsa.dev/provenance/v1"}}}`, `"dist":{}`, 1), "", nil, []string{"npm.provenance-lost"}},
		{"manifest confusion", basePkg, strings.Replace(basePkg, `"dependencies":{"a":"^1"}`, `"dependencies":{}`, 1), nil, []string{"npm.manifest-mismatch"}},
		{"native", basePkg, "", map[string]string{"binding.gyp": "{}", "build/x.node": "\x7fELF\x02", "bin/tool": "\x7fELF\x02"}, []string{"npm.executable", "npm.native-addon"}},
		{"minified new file", basePkg, "", map[string]string{"dist/x.min.js": minified}, []string{"npm.minified-new-file"}},
		{"obfuscated", basePkg, "", map[string]string{"lib.js": strings.Repeat("var _0x1a2b3c=_0x4d5e6f[0x1];\n", 20)}, []string{"npm.obfuscated"}},
	}
	old := mkSide(t, basePkg, nil, "")
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cur := mkSide(t, tt.pkg, tt.extra, tt.doc)
			var got []string
			for _, f := range checkPackage(old, cur) {
				got = append(got, f.Code)
				if f.Route != model.RouteHuman {
					t.Errorf("%s route %s", f.Code, f.Route)
				}
			}
			slices.Sort(got)
			if !slices.Equal(got, tt.want) {
				t.Errorf("codes = %q, want %q", got, tt.want)
			}
		})
	}
}

// fakeRegistry serves version documents and tarballs for name@version.
func fakeRegistry(t *testing.T, pkgs map[string][]byte, tamper map[string]bool) *httptest.Server {
	t.Helper()
	var srv *httptest.Server
	srv = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		p := strings.TrimPrefix(r.URL.EscapedPath(), "/")
		if strings.HasPrefix(p, "tgz/") {
			key := strings.TrimPrefix(p, "tgz/")
			b := pkgs[key]
			if tamper[key] {
				b = append(slices.Clone(b), 0)
			}
			w.Write(b)
			return
		}
		name, ver, _ := strings.Cut(strings.Replace(p, "%2f", "/", 1), "/")
		if strings.HasPrefix(name, "@") {
			n2, v2, _ := strings.Cut(ver, "/")
			name, ver = name+"/"+n2, v2
		}
		key := name + "@" + ver
		b, ok := pkgs[key]
		if !ok {
			http.NotFound(w, r)
			return
		}
		sum := sha512.Sum512(b)
		s1 := sha1.Sum(b)
		json.NewEncoder(w).Encode(map[string]any{
			"name": name, "version": ver, "_npmUser": map[string]string{"name": "alice", "email": "a@x"},
			"dist": map[string]string{"tarball": srv.URL + "/tgz/" + key, "integrity": "sha512-" + base64.StdEncoding.EncodeToString(sum[:]), "shasum": fmt.Sprintf("%x", s1)},
		})
	}))
	t.Cleanup(srv.Close)
	return srv
}

func tgz(t *testing.T, files map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	tw := tar.NewWriter(zw)
	for name, data := range files {
		tw.WriteHeader(&tar.Header{Name: "package/" + name, Mode: 0o644, Size: int64(len(data)), Typeflag: tar.TypeReg})
		tw.Write([]byte(data))
	}
	tw.Close()
	zw.Close()
	return buf.Bytes()
}

func integrity(b []byte) string {
	s := sha512.Sum512(b)
	return "sha512-" + base64.StdEncoding.EncodeToString(s[:])
}

func TestVerifyAndDiffFakeRegistry(t *testing.T) {
	v1 := tgz(t, map[string]string{"package.json": `{"name":"p","version":"1.0.0"}`, "index.js": "module.exports = 1\n"})
	v2 := tgz(t, map[string]string{"package.json": `{"name":"p","version":"1.0.1"}`, "index.js": "module.exports = 2\n"})
	pkgs := map[string][]byte{"p@1.0.0": v1, "p@1.0.1": v2}
	tests := []struct {
		name     string
		tamper   map[string]bool
		lockInt  string
		wantCode string
	}{
		{"clean", nil, integrity(v2), ""},
		{"lockfile integrity differs from registry", nil, integrity([]byte("other")), "npm.integrity-mismatch"},
		{"tarball bytes differ", map[string]bool{"p@1.0.1": true}, integrity(v2), "npm.integrity-mismatch"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			srv := fakeRegistry(t, pkgs, tt.tamper)
			ev, err := evidence.Create(filepath.Join(t.TempDir(), "ev"))
			if err != nil {
				t.Fatal(err)
			}
			defer ev.Close()
			env := fetch.Env{Scratch: t.TempDir(), Evidence: ev, HTTP: srv.Client()}
			c := change{
				update: model.Update{Name: "p", From: "1.0.0", To: "1.0.1", Directory: "/"},
				base:   Entry{Integrity: integrity(v1)},
				head:   Entry{Integrity: tt.lockInt},
			}
			var sum bytes.Buffer
			fs, err := Fetcher{Registry: srv.URL}.verifyAndDiff(context.Background(), env, t.TempDir(), filepath.Join(env.Scratch, "w"), c, &sum)
			if err != nil {
				t.Fatal(err)
			}
			var codes []string
			for _, f := range fs {
				codes = append(codes, f.Code)
			}
			if tt.wantCode == "" {
				if len(fs) != 0 {
					t.Errorf("findings %+v", fs)
				}
				files := ev.Files()
				if len(files) != 1 || !files[0].Untrusted {
					t.Fatalf("files = %+v", files)
				}
				return
			}
			if !slices.Contains(codes, tt.wantCode) {
				t.Errorf("codes %q lack %s", codes, tt.wantCode)
			}
			for _, f := range fs {
				if f.Code == tt.wantCode && f.Route != model.RouteRefuse {
					t.Errorf("%s route %s, want refuse", f.Code, f.Route)
				}
			}
		})
	}
}

// TestFetchNetwork runs sadbox/towngear#40 (@tailwindcss/cli 4.3.4 -> 4.3.5)
// end to end against registry.npmjs.org.
func TestFetchNetwork(t *testing.T) {
	if testing.Short() {
		t.Skip("network")
	}
	repo, class := fixtureRepo(t, "towngear40", nil)
	class.Declared = []model.Update{{Name: "@tailwindcss/cli", From: "4.3.4", To: "4.3.5"}}
	out := filepath.Join(t.TempDir(), "ev")
	ev, err := evidence.Create(out)
	if err != nil {
		t.Fatal(err)
	}
	defer ev.Close()
	env := fetch.Env{Class: class, RepoDir: repo, Scratch: t.TempDir(), HTTP: ecoutil.NewClient()}
	res, err := fetch.Run(context.Background(), env, fetch.Registry{model.NPM: Fetcher{}}, ev)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("route %s, %d updates, truncated %v", res.Route, len(res.Updates), res.Truncated)
	for _, f := range res.Findings {
		t.Logf("finding %s %s: %s", f.Code, f.Route, f.Detail)
	}
	for _, f := range res.Files {
		t.Logf("file %s (%d bytes)", f.Path, f.Bytes)
	}
	// The oxide platform packages ship native .node binaries.
	if res.Route != model.RouteHuman {
		t.Errorf("route = %s, want human", res.Route)
	}
	for _, f := range res.Findings {
		if f.Route == model.RouteRefuse {
			t.Errorf("unexpected refusal: %+v", f)
		}
	}
}
