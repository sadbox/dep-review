func fixtureRepo(t *testing.T, name string, edit func(head map[string][]byte)) (string, model.Classification) {
	t.Helper()
	base := gittest.ReadDir(t, filepath.Join("testdata", name, "base"))
	head := gittest.ReadDir(t, filepath.Join("testdata", name, "head"))
	if edit != nil {
		edit(head)
	}
	dir, b, h := gittest.Repo(t, base, head)
	return dir, model.Classification{Repo: "test/" + name, PR: 1, BaseSHA: b, HeadSHA: h, Kind: model.KindDependabot, Ecosystem: model.NPM}
}

func TestChangeSetFixture(t *testing.T) {
	repo, class := fixtureRepo(t, "towngear40", nil)
	git := ecoutil.Git{Repo: repo, Home: t.TempDir()}
	var sum bytes.Buffer
	changes, findings, err := dirChanges(context.Background(), git, class.BaseSHA, class.HeadSHA, ".", &sum)
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 0 {
		t.Errorf("findings %+v", findings)
	}
	var got []string
	for _, c := range changes {
		got = append(got, fmt.Sprintf("%s %s->%s %s direct=%v", c.update.Name, c.update.From, c.update.To, c.update.Type, c.update.Direct))
		if c.head.Integrity == "" || c.base.Integrity == "" {
			t.Errorf("%s: missing lockfile entries", c.update.Name)
		}
	}
	want := []string{
		"@tailwindcss/cli 4.3.4->4.3.5 patch direct=true",
		"@tailwindcss/node 4.3.4->4.3.5 patch direct=false",
		"@tailwindcss/oxide 4.3.4->4.3.5 patch direct=false",
	}
	for _, w := range want {
		if !slices.Contains(got, w) {
			t.Errorf("missing %q in %q", w, got)
		}
	}
	for _, g := range got {
		if strings.HasPrefix(g, "tailwindcss ") {
			t.Errorf("tailwindcss only lost a nested duplicate, got update %q", g)
		}
	}
	if !strings.Contains(sum.String(), "tailwindcss 4.3.4: removed") {
		t.Errorf("summary lacks the removed duplicate:\n%s", sum.String())
	}
}

