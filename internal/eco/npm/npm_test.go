func TestParsePackageLockFixture(t *testing.T) {
	b, err := os.ReadFile("testdata/towngear40/head/package-lock.json")
	if err != nil {
		t.Fatal(err)
	}
	l, err := ParsePackageLock(b)
	if err != nil {
		t.Fatal(err)
	}
	if !l.Direct["@tailwindcss/cli"] || !l.Direct["tailwindcss"] {
		t.Errorf("Direct = %v", l.Direct)
	}
	var cli *Entry
	for i, e := range l.Entries {
		if e.Location == "node_modules/@tailwindcss/cli" {
			cli = &l.Entries[i]
		}
	}
	if cli == nil || cli.Name != "@tailwindcss/cli" || cli.Version != "4.3.5" || sha512Of(cli.Integrity) == nil ||
		cli.Resolved != "https://registry.npmjs.org/@tailwindcss/cli/-/cli-4.3.5.tgz" {
		t.Errorf("cli entry = %+v", cli)
	}
	if _, err := ParsePackageLock([]byte(`{"lockfileVersion":1,"dependencies":{}}`)); err == nil {
		t.Error("lockfile v1 accepted")
	}
}

